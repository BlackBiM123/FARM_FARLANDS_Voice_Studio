export function guideSectionText(s: GuideSection): string {
  return [
    s.title,
    ...(s.paragraphs ?? []),
    ...(s.steps ?? []),
    ...(s.bullets ?? []),
    ...(s.table?.headers ?? []),
    ...(s.table?.rows.flat() ?? []),
    s.note?.title ?? "",
    s.note?.text ?? "",
  ].join(" ");
}
export function normalizeGuideText(text: string) {
  return text.toLocaleLowerCase("ru").replaceAll("ё", "е");
}
export function searchGuide(query: string) {
  const words = normalizeGuideText(query.trim()).split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  return guideChapters.flatMap((chapter) =>
    chapter.sections
      .filter((section) => {
        const text = normalizeGuideText(
          chapter.title + " " + guideSectionText(section),
        );
        return words.every((w) => text.includes(w));
      })
      .map((section) => ({
        chapter,
        section,
        text: guideSectionText(section),
      })),
  );
}
